#!/usr/bin/env python3
"""Prepare local Android/Windows assets, platform changelogs and channel-reference candidates. Never publishes."""
import argparse
import json
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

import generate_manifest as android


def notes(path):
    value = path.read_text(encoding="utf-8-sig").strip()
    if not value or len(value) > 20_000:
        raise ValueError("Changelog must contain 1..20000 characters: " + str(path))
    return value


def windows_identity(exe):
    """Read the installer's actual version resource; never trust its filename as version evidence."""
    if os.name != "nt":
        raise ValueError("Windows installer inspection requires Windows")
    environment = os.environ.copy()
    environment["SQUITV_INSPECT_EXE"] = str(exe)
    # Static script + environment path: no interpolation of filenames as PowerShell code.
    command = "$v=[Diagnostics.FileVersionInfo]::GetVersionInfo($env:SQUITV_INSPECT_EXE); @{ProductName=$v.ProductName;ProductVersion=$v.ProductVersion}|ConvertTo-Json -Compress"
    result = subprocess.run(["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", command],
        env=environment, capture_output=True, text=True, encoding="utf-8", errors="strict", timeout=30,
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    if result.returncode:
        raise ValueError("Cannot read Windows installer version resource")
    return json.loads(result.stdout)


def windows_artifact(exe, metadata_path):
    if metadata_path.stat().st_size > 4096:
        raise ValueError("Windows build metadata too large")
    record = json.loads(metadata_path.read_text(encoding="utf-8"))
    if (record.get("schemaVersion") != 1 or record.get("variant") != "release" or
            record.get("applicationName") != "SquiTV" or record.get("platform") != "windows" or
            record.get("kind") != "exe" or record.get("architecture") not in ("x64", "arm64")):
        raise ValueError("Use Windows release metadata generated by :desktopApp:writeUpdateMetadata")
    identity = windows_identity(exe)
    version = record.get("versionName", "")
    android.version_parts(version)
    if len(version.split(".")) != 3 or version.startswith(("v", "V")):
        raise ValueError("Windows package version must have three numeric components")
    if identity != {"ProductName": "SquiTV Installer", "ProductVersion": version}:
        raise ValueError("Installer product/version does not match release build metadata")
    if (exe.name != "SquiTV-" + version + ".exe" or record.get("assetName") != exe.name or
            record.get("sizeBytes") != exe.stat().st_size or record.get("sha256") != android.sha256(exe)):
        raise ValueError("Installer bytes/name do not match the recorded release build")
    with exe.open("rb") as source:
        if source.read(2) != b"MZ":
            raise ValueError("Installer is not a Windows executable")
    if not 1 <= exe.stat().st_size <= 600 * 1024 * 1024:
        raise ValueError("Installer outside client size bounds")
    return {key: record[key] for key in ("platform", "kind", "architecture", "versionName", "assetName", "sizeBytes", "sha256")}


def encode(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def prepare(args):
    if not args.android and not args.windows:
        raise ValueError("Choose --android, --windows or both")
    if bool(args.android) != bool(args.android_notes) or bool(args.windows) != bool(args.windows_notes):
        raise ValueError("Each included platform requires its own changelog; omit notes for absent platforms")
    if bool(args.windows) != bool(args.windows_metadata):
        raise ValueError("Windows requires --windows-metadata from :desktopApp:writeUpdateMetadata")
    artifacts, changelogs, sources = [], {}, {}
    if args.android:
        sdk = android.find_sdk(args.sdk)
        aapt, _ = android.find_tools(sdk)
        metadata = android.parse_badging(android.run_tool([aapt, "dump", "badging", args.android]))
        android_version = metadata["versionName"]
        changelogs["android"] = notes(args.android_notes)
    if args.windows:
        artifact = windows_artifact(args.windows.resolve(), args.windows_metadata)
        artifacts.append(artifact)
        sources[artifact["assetName"]] = args.windows.resolve()
        changelogs["windows"] = notes(args.windows_notes)
    if args.android and args.windows:
        if android.version_parts(android_version) != android.version_parts(artifact["versionName"]):
            raise ValueError("Joint release requires the same application version on Android and Windows")
        if android.version_parts(android_version)[2:] != (0, 0):
            raise ValueError("Joint releases use a new minor version, e.g. Android 1.22 / Windows 1.22.0")
        tag, title, latest = "v" + android_version, "Squi TV v" + android_version + " — Android e Windows", True
    elif args.android:
        tag, title, latest = "v" + android_version, "Squi TV — Android v" + android_version, True
    else:
        version = artifact["versionName"]
        # Keep tags numeric for distributed Android v1.21 clients; reserve fourth component for Windows.
        tag, title, latest = "v" + version + ".1", "Squi TV — Windows v" + version, False
    if args.tag and args.tag != tag:
        raise ValueError("Publication mode requires tag " + tag)
    with tempfile.TemporaryDirectory(prefix="squitv-stage-") as temp:
        temporary = Path(temp)
        if args.android:
            _, result = android.generate(args.android, tag, sdk, temporary / "android")
            android_artifact = result["artifacts"][0]
            artifacts.insert(0, android_artifact)
            sources[android_artifact["assetName"]] = temporary / "android" / android_artifact["assetName"]
        manifest = dict(schemaVersion=1, productId="squi-tv", channel="stable", releaseTag=tag,
                        artifacts=artifacts, changelogs=changelogs)
        payload = encode(manifest)
        if len(payload) > 262_144:
            raise ValueError("Manifest exceeds client size limit")
        manifest_hash = hashlib.sha256(payload).hexdigest()
        files = {Path("upload/squitv-update.json"): payload}
        for item in artifacts:
            name = item["assetName"]
            files[Path("upload") / (name + ".sha256")] = (item["sha256"] + "  " + name + "\n").encode()
        for platform, text in changelogs.items():
            version = next(item["versionName"] for item in artifacts if item["platform"] == platform)
            reference = dict(schemaVersion=1, productId="squi-tv", channel="stable", platform=platform,
                             versionName=version, releaseTag=tag, manifestSha256=manifest_hash)
            files[Path("channel-index") / (platform + ".json")] = encode(reference)
        body = "# " + title + "\n\n" + "\n\n".join("## " + platform.title() + "\n\n" + text for platform, text in changelogs.items()) + "\n"
        files[Path("release-notes.md")] = body.encode("utf-8")
        files[Path("release-plan.json")] = encode(dict(tag=tag, name=title, makeLatest=latest, draft=True, prerelease=False,
            platforms=list(changelogs), uploadAssets=["squitv-update.json"] +
            [name for item in artifacts for name in (item["assetName"], item["assetName"] + ".sha256")],
            channelReferences="Publish release/assets first; only then update updates/stable/<platform>.json"))
        output = args.output_dir.resolve()
        # Preflight every output before copying. Existing different artifacts are never replaced.
        for relative, contents in files.items():
            path = output / relative
            if path.exists() and path.read_bytes() != contents:
                raise FileExistsError("Different staged metadata exists: " + str(path))
        for name, source in sources.items():
            path = output / "upload" / name
            if path.exists() and android.sha256(path) != android.sha256(source):
                raise FileExistsError("Different staged binary exists: " + str(path))
        upload = output / "upload"
        expected_names = {path.name for path in files if path.parent == Path("upload")} | set(sources)
        if upload.exists() and any(path.name not in expected_names for path in upload.iterdir()):
            raise FileExistsError("Upload directory contains unrelated files; choose a new staging directory")
        upload.mkdir(parents=True, exist_ok=True)
        for name, source in sources.items():
            path = upload / name
            if not path.exists():
                shutil.copyfile(source, path)
            if android.sha256(path) != android.sha256(source):
                raise ValueError("Staged artifact integrity mismatch")
        for relative, contents in files.items():
            if relative == Path("release-plan.json"):
                continue
            path = output / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)
        # Write the reviewable plan last, after all binary and metadata outputs are complete.
        (output / "release-plan.json").write_bytes(files[Path("release-plan.json")])
    return output / "release-plan.json"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--android", type=Path)
    parser.add_argument("--windows", type=Path)
    parser.add_argument("--windows-metadata", type=Path)
    parser.add_argument("--android-notes", type=Path)
    parser.add_argument("--windows-notes", type=Path)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--sdk", type=Path)
    parser.add_argument("--tag")
    args = parser.parse_args()
    try:
        print(prepare(args))
    except (ValueError, OSError, KeyError, android.subprocess.TimeoutExpired, android.zipfile.BadZipFile) as error:
        parser.exit(1, str(error) + "\n")


if __name__ == "__main__":
    main()
